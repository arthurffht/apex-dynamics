[CmdletBinding()]
param([string]$EngineProfile)
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'lib/Project.psm1') -Force
$root = Get-ApexRoot
$output = Join-Path $root '.local/generated'
$project = Get-Content -LiteralPath (Join-Path $root 'default.project.json') -Raw | ConvertFrom-Json -AsHashtable
if(-not $EngineProfile){$EngineProfile=Join-Path $root 'config/engine.json'}
$engine = Get-Content -LiteralPath $EngineProfile -Raw | ConvertFrom-Json
$authorityValues = @{Server=0;Automatic=1}
$rolloutValues = @{Default=0;Disabled=1;Enabled=2}
$steppingValues = @{Default=0;Fixed=1;Adaptive=2}
if (-not $authorityValues.ContainsKey($engine.authorityMode) -or -not $rolloutValues.ContainsKey($engine.fixedSimulation) -or -not $steppingValues.ContainsKey($engine.physicsSteppingMethod)) { throw 'Invalid engine profile' }
if ($engine.authorityMode -ne 'Automatic' -or $engine.fixedSimulation -eq 'Enabled') {
    throw 'The current vehicle adapter supports conventional Automatic authority only. Rollback Server Authority requires a replay-safe adapter; changing a property does not implement it.'
}
[IO.Directory]::CreateDirectory($output) | Out-Null
$snapshot = Get-ApexSourceSnapshot
$info = "--!strict`n-- Generated by scripts/generate-project.ps1. Edit source files, not this artifact.`nreturn table.freeze({ fingerprint = `"$($snapshot.fingerprint)`" })`n"
[IO.File]::WriteAllText((Join-Path $output 'BuildInfo.luau'),$info)
$snapshot | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $output 'source-snapshot.json') -Encoding utf8
$properties = $project.tree.Workspace.'$properties'
$properties.AuthorityMode = @{Enum=$authorityValues[$engine.authorityMode]}
$properties.UseFixedSimulation = @{Enum=$rolloutValues[$engine.fixedSimulation]}
$properties.PhysicsSteppingMethod = @{Enum=$steppingValues[$engine.physicsSteppingMethod]}
$properties.StreamingEnabled = [bool]$engine.streamingEnabled
$project.serveAddress = '127.0.0.1'
$project.servePort = 34872
$project.servePlaceIds = @(0)
function Resolve-Paths($node) {
    if ($node -is [System.Collections.IDictionary]) {
        foreach ($key in @($node.Keys)) {
            if ($key -eq '$path') { $node[$key] = [IO.Path]::GetFullPath((Join-Path $root $node[$key])) }
            else { Resolve-Paths $node[$key] }
        }
    }
}
Resolve-Paths $project
$project | ConvertTo-Json -Depth 30 | Set-Content -LiteralPath (Join-Path $output 'active.project.json') -Encoding utf8
Write-Output "Generated local-only Rojo project; source $($snapshot.fingerprint.Substring(0,12))"
